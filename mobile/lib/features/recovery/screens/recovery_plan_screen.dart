  @override
  State<RecoveryPlanScreen> createState() => _RecoveryPlanScreenState();
}

class _RecoveryPlanScreenState extends State<RecoveryPlanScreen> {
  final RecoveryApiService _api = RecoveryApiService();
  RecoveryRequestModel? _recovery;
  bool _isLoading = true;
  bool _isGenerating = false;
  bool _isSubmitting = false;
  bool _isTogglingChecklist = false;
  String? _errorMessage;
  String? _successMessage;

  @override
  void initState() {
    super.initState();
    _loadRecovery();
  }

  Future<void> _loadRecovery() async {
    setState(() => _isLoading = true);
    try {
      final data = await _api.getRecoveryRequest(widget.recoveryId);
      if (mounted) {
        setState(() => _recovery = data);
        if (data.plan == null && (data.status == 'Draft' || data.status == 'PlanGenerated')) {
          _generatePlan();
        }
      }
    } on DioException catch (e) {
      final body = e.response?.data;
      final msg = body is Map ? (body['error'] ?? body['title'] ?? e.message) : (e.message ?? 'Failed to load recovery plan.');
      if (mounted) setState(() => _errorMessage = msg.toString());
    } catch (e) {
      if (mounted) setState(() => _errorMessage = 'Failed to load recovery plan: $e');
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  Future<void> _generatePlan() async {
    setState(() {
      _isGenerating = true;
      _errorMessage = null;
      _successMessage = null;
    });
    try {
      final updated = await _api.generateRecoveryPlan(widget.recoveryId);
      if (mounted) {
        setState(() {
          _recovery = updated;
          _successMessage = 'Recovery plan generated by Agent 2.';
        });
      }
    } on DioException catch (e) {
      final body = e.response?.data;
      final msg = body is Map ? (body['error'] ?? body['title'] ?? e.message) : (e.message ?? 'Plan generation failed.');
      if (mounted) setState(() => _errorMessage = msg.toString());
    } catch (e) {
      if (mounted) {
        setState(() => _errorMessage = 'Plan generation failed: $e');
      }
    } finally {
      if (mounted) setState(() => _isGenerating = false);
    }
  }

  Future<void> _toggleChecklist(PreCollectionChecklistItem item, bool newValue) async {
    if (_isTogglingChecklist) return;
    // Optimistic update
    setState(() {
      _isTogglingChecklist = true;
      item.isCompleted = newValue;
      if (_recovery?.plan != null) {
        final allMandatory = _recovery!.plan!.checklist.where((c) => c.isMandatory).every((c) => c.isCompleted);
        _recovery!.plan!.isPreparationVerified = allMandatory;
      }
    });
    try {
      final resp = await _api.toggleChecklistStep(widget.recoveryId, item.id, newValue);
      if (mounted && resp != null && _recovery?.plan != null) {
        // Update isPreparationVerified from server response
        final isVerified = resp['isPreparationVerified'] as bool? ?? false;
        // Update each checklist item from server response if available
        final serverChecklist = resp['checklist'];
        if (serverChecklist is List) {
          for (final sc in serverChecklist) {
            final match = _recovery!.plan!.checklist.where((c) => c.id == (sc['id'] ?? '')).toList();
            if (match.isNotEmpty) {
              match.first.isCompleted = sc['isCompleted'] ?? false;
            }
          }
        }
        setState(() {
          _recovery!.plan!.isPreparationVerified = isVerified;
        });
      }
    } catch (_) {
      if (mounted) {
        setState(() {
          item.isCompleted = !newValue;
          if (_recovery?.plan != null) {
            final allMandatory = _recovery!.plan!.checklist.where((c) => c.isMandatory).every((c) => c.isCompleted);
            _recovery!.plan!.isPreparationVerified = allMandatory;
          }
          _errorMessage = 'Failed to update checklist step.';
        });
      }
    } finally {
      if (mounted) setState(() => _isTogglingChecklist = false);
    }
  }

  Future<void> _submitForAdminReview() async {
    final plan = _recovery?.plan;
    if (plan != null && !plan.isPreparationVerified) {
      setState(() => _errorMessage = 'Please complete all mandatory preparation checklist steps before submitting for admin review.');
      return;
    }

    setState(() {
      _isSubmitting = true;
      _errorMessage = null;
      _successMessage = null;
    });
    try {
      await _api.submitForAdminApproval(widget.recoveryId);
      if (mounted) {
        setState(() => _successMessage = 'Submitted for Admin approval.');
        await _loadRecovery();
      }
    } on DioException catch (e) {
      final body = e.response?.data;
      final msg = body is Map ? (body['error'] ?? body['title'] ?? e.message) : (e.message ?? 'Submission failed.');
      if (mounted) setState(() => _errorMessage = msg.toString());
    } catch (e) {
      if (mounted) setState(() => _errorMessage = 'Submission failed: $e');
    } finally {
      if (mounted) setState(() => _isSubmitting = false);
    }
  }

