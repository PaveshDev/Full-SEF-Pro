                                              Text(item.description, style: const TextStyle(fontSize: 11, color: AppColors.slateLight, height: 1.4)),
                                            ],
                                          ],
                                        ),
                                      ),
                                    ],
                                  ),
                                ),
                              )),
                        ],
                      ),
                    );
                  }),
                ],

                // Bottom Action Bar
                if (plan != null) ...[
                  const Divider(),
                  const SizedBox(height: 12),
                  Row(
                    mainAxisAlignment: MainAxisAlignment.spaceBetween,
                    children: [
                      // Left: Regenerate (only in draft)
                      if (isDraft)
                        OutlinedButton.icon(
                          onPressed: _isGenerating ? null : _generatePlan,
                          icon: const Icon(Icons.auto_awesome, size: 14),
                          label: const Text('Regenerate Plan'),
                          style: OutlinedButton.styleFrom(
                            padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 10),
                            foregroundColor: AppColors.primary,
                            side: const BorderSide(color: AppColors.primary),
                          ),
                        )
                      else
                        const SizedBox(),

                      // Right: Submit for Admin Review or Proceed to Matching
                      if (isApproved)
                        Expanded(
                          child: Padding(
                            padding: const EdgeInsets.only(left: 8),
                            child: ElevatedButton.icon(
                              onPressed: () {
                                context.push('/matching-partners?recoveryId=${recovery.id}');
                              },
                              icon: const Icon(Icons.handshake_outlined, color: Colors.white),
                              label: const Text(
                                'Proceed to Certified Partner Matching',
                                style: TextStyle(fontWeight: FontWeight.bold, fontSize: 14, color: Colors.white),
                              ),
                              style: ElevatedButton.styleFrom(
                                backgroundColor: AppColors.primary,
                                padding: const EdgeInsets.symmetric(vertical: 14),
                                shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
                              ),
                            ),
                          ),
                        )
                      else if (isDraft || isRevision) ...[
                        if (!(plan.isPreparationVerified))
                          Row(
                            mainAxisSize: MainAxisSize.min,
                            children: [
                              const Text(
                                'Check all required items to enable review: ',
                                style: TextStyle(fontSize: 12, color: AppColors.slateLight),
                              ),
                              Tooltip(
                                message: 'Complete all required checklist items first',
                                child: ElevatedButton.icon(
                                  onPressed: null,
                                  icon: const Icon(Icons.lock_outline, size: 16, color: Colors.white70),
                                  label: const Text('Submit for Admin Review', style: TextStyle(color: Colors.white70, fontWeight: FontWeight.bold)),
                                  style: ElevatedButton.styleFrom(
                                    backgroundColor: AppColors.primary.withAlpha(90),
                                    padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 14),
                                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
                                  ),
                                ),
                              ),
                            ],
                          )
                        else
                          ElevatedButton.icon(
                            onPressed: _isSubmitting ? null : _submitForAdminReview,
                            icon: _isSubmitting
                                ? const SizedBox(width: 16, height: 16, child: CircularProgressIndicator(strokeWidth: 2, color: Colors.white))
                                : const Icon(Icons.shield_outlined, size: 16, color: Colors.white),
                            label: Text(
                              _isSubmitting ? 'Submitting...' : 'Submit for Admin Review',
                              style: const TextStyle(fontWeight: FontWeight.bold, color: Colors.white),
                            ),
                            style: ElevatedButton.styleFrom(
                              backgroundColor: AppColors.primary,
                              padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 14),
                              shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
                            ),
                          ),
                      ],
                    ],
                  ),
                ],
              ],
            ),
          ),
        ),
      ),
    );
  }
